package com.portfolio.roombooking.booking;

import com.portfolio.roombooking.booking.dto.BookingRequest;
import com.portfolio.roombooking.common.BusinessRuleException;
import com.portfolio.roombooking.common.ConflictException;
import com.portfolio.roombooking.room.Room;
import com.portfolio.roombooking.room.RoomRepository;
import com.portfolio.roombooking.user.Role;
import com.portfolio.roombooking.user.User;
import com.portfolio.roombooking.user.UserRepository;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InOrder;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.security.access.AccessDeniedException;
import org.springframework.test.util.ReflectionTestUtils;

import java.time.*;
import java.util.List;
import java.util.Optional;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyLong;
import static org.mockito.ArgumentMatchers.eq;
import static org.mockito.Mockito.*;

/**
 * UNIT tests for BookingService: the repositories are Mockito mocks, so no Spring context and no
 * database start - each test runs in milliseconds and focuses on ONE rule.
 *
 * <ul>
 *   <li>{@code when(...).thenReturn(...)} scripts what a mock returns;</li>
 *   <li>{@code verify(...)} asserts a mock was called (or {@code never()} called);</li>
 *   <li>the Clock is fixed at Wednesday 2026-10-14 09:00 so "past/future" is deterministic.</li>
 * </ul>
 * The real SQL overlap query is exercised by the integration test instead (mocks cannot test SQL).
 */
@ExtendWith(MockitoExtension.class)
class BookingServiceTest {

    private static final Clock FIXED_CLOCK = Clock.fixed(Instant.parse("2026-10-14T09:00:00Z"), ZoneOffset.UTC);
    private static final LocalDateTime TOMORROW_10 = LocalDateTime.of(2026, 10, 15, 10, 0);
    private static final LocalDateTime TOMORROW_11 = LocalDateTime.of(2026, 10, 15, 11, 0);

    @Mock private BookingRepository bookings;
    @Mock private RoomRepository rooms;
    @Mock private UserRepository users;

    private BookingService service;
    private User alice;
    private User bob;
    private User admin;
    private Room room;

    @BeforeEach
    void setUp() {
        service = new BookingService(bookings, rooms, users, new BookingTimeRules(FIXED_CLOCK), FIXED_CLOCK);
        alice = user(1L, "Alice", Role.USER);
        bob = user(2L, "Bob", Role.USER);
        admin = user(3L, "Ada", Role.ADMIN);
        room = new Room("Atlas", "Floor 3", 6);
        ReflectionTestUtils.setField(room, "id", 10L);   // ids are normally generated by the DB
    }

    private static User user(long id, String name, Role role) {
        User u = new User(name, name.toLowerCase() + "@example.com", "hash", role);
        ReflectionTestUtils.setField(u, "id", id);
        return u;
    }

    private static BookingRequest request(LocalDateTime start, LocalDateTime end, int attendees) {
        return new BookingRequest(10L, "  Sprint planning ", null, start, end, attendees);
    }

    /** Stubs the two lock queries the service calls for every create/reschedule. */
    private void stubLocks(User owner) {
        when(rooms.findByIdForUpdate(10L)).thenReturn(Optional.of(room));
        when(users.findByIdForUpdate(owner.getId())).thenReturn(Optional.of(owner));
    }

    private Booking existingBooking(User owner, LocalDateTime start, LocalDateTime end) {
        Booking b = new Booking(room, owner);
        ReflectionTestUtils.setField(b, "id", 42L);
        b.setTitle("Existing");
        b.setStartTime(start);
        b.setEndTime(end);
        b.setAttendees(2);
        return b;
    }

    @Test
    void create_locksRoomThenUser_checksOverlaps_andSaves() {
        stubLocks(alice);
        when(bookings.saveAndFlush(any(Booking.class))).thenAnswer(inv -> inv.getArgument(0));

        var response = service.create(alice, request(TOMORROW_10, TOMORROW_11, 4));

        assertThat(response.title()).isEqualTo("Sprint planning");      // trimmed
        assertThat(response.status()).isEqualTo(BookingStatus.CONFIRMED);
        // The lock order matters (room first, then user) to avoid deadlocks - verify it.
        InOrder order = inOrder(rooms, users, bookings);
        order.verify(rooms).findByIdForUpdate(10L);
        order.verify(users).findByIdForUpdate(1L);
        order.verify(bookings).findRoomConflicts(10L, TOMORROW_10, TOMORROW_11, BookingRepository.NO_ID);
        order.verify(bookings).saveAndFlush(any(Booking.class));
    }

    @Test
    void create_rejectsOverlapWithAnotherBookingInTheRoom_with409() {
        stubLocks(alice);
        when(bookings.findRoomConflicts(eq(10L), any(), any(), anyLong()))
                .thenReturn(List.of(existingBooking(bob, TOMORROW_10, TOMORROW_11)));

        assertThatThrownBy(() -> service.create(alice, request(TOMORROW_10.plusMinutes(30), TOMORROW_11.plusMinutes(30), 2)))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("already booked from 10:00 to 11:00")
                .hasMessageNotContaining("Existing");   // never leak someone else's meeting title
        verify(bookings, never()).saveAndFlush(any());
    }

    @Test
    void create_rejectsWhenTheUserIsAlreadyInAnotherMeeting() {
        stubLocks(alice);
        Room other = new Room("Nova", "Floor 2", 4);
        Booking clash = existingBooking(alice, TOMORROW_10, TOMORROW_11);
        clash.setRoom(other);
        when(bookings.findUserConflicts(eq(1L), any(), any(), anyLong())).thenReturn(List.of(clash));

        assertThatThrownBy(() -> service.create(alice, request(TOMORROW_10, TOMORROW_11, 2)))
                .isInstanceOf(ConflictException.class)
                .hasMessageContaining("You already have a booking in 'Nova'");
    }

    @Test
    void create_rejectsMoreAttendeesThanCapacity() {
        stubLocks(alice);
        assertThatThrownBy(() -> service.create(alice, request(TOMORROW_10, TOMORROW_11, 7)))
                .isInstanceOf(BusinessRuleException.class)
                .hasMessageContaining("holds at most 6 people");
    }

    @Test
    void create_rejectsInactiveRoom() {
        room.setActive(false);
        stubLocks(alice);
        assertThatThrownBy(() -> service.create(alice, request(TOMORROW_10, TOMORROW_11, 2)))
                .isInstanceOf(BusinessRuleException.class)
                .hasMessageContaining("not available for booking");
    }

    @Test
    void create_rejectsInvalidTimes_beforeTouchingTheDatabase() {
        assertThatThrownBy(() -> service.create(alice, request(TOMORROW_10, TOMORROW_10.plusMinutes(10), 2)))
                .isInstanceOf(BusinessRuleException.class);
        verifyNoInteractions(rooms, users, bookings);   // no lock taken for an obviously invalid request
    }

    @Test
    void reschedule_excludesTheBookingItselfFromTheOverlapCheck() {
        Booking mine = existingBooking(alice, TOMORROW_10, TOMORROW_11);
        when(bookings.findWithDetailsById(42L)).thenReturn(Optional.of(mine));
        stubLocks(alice);
        when(bookings.saveAndFlush(mine)).thenReturn(mine);

        var response = service.reschedule(alice, 42L, request(TOMORROW_10.plusMinutes(30), TOMORROW_11.plusMinutes(30), 2));

        verify(bookings).findRoomConflicts(10L, TOMORROW_10.plusMinutes(30), TOMORROW_11.plusMinutes(30), 42L);
        verify(bookings).findUserConflicts(1L, TOMORROW_10.plusMinutes(30), TOMORROW_11.plusMinutes(30), 42L);
        assertThat(response.startTime()).isEqualTo(TOMORROW_10.plusMinutes(30));
    }

    @Test
    void cancel_byAnotherUser_isForbidden() {
        when(bookings.findWithDetailsById(42L)).thenReturn(Optional.of(existingBooking(alice, TOMORROW_10, TOMORROW_11)));

        assertThatThrownBy(() -> service.cancel(bob, 42L))
                .isInstanceOf(AccessDeniedException.class)
                .hasMessageContaining("your own bookings");
    }

    @Test
    void cancel_byAdmin_isAllowed_andMarksTheBookingCancelled() {
        Booking b = existingBooking(alice, TOMORROW_10, TOMORROW_11);
        when(bookings.findWithDetailsById(42L)).thenReturn(Optional.of(b));

        var response = service.cancel(admin, 42L);

        assertThat(response.status()).isEqualTo(BookingStatus.CANCELLED);
        assertThat(b.getStatus()).isEqualTo(BookingStatus.CANCELLED);
    }

    @Test
    void cancel_aBookingThatAlreadyStarted_isRejected() {
        LocalDateTime earlierToday = LocalDateTime.of(2026, 10, 14, 8, 30);
        when(bookings.findWithDetailsById(42L))
                .thenReturn(Optional.of(existingBooking(alice, earlierToday, earlierToday.plusHours(1))));

        assertThatThrownBy(() -> service.cancel(alice, 42L))
                .isInstanceOf(BusinessRuleException.class)
                .hasMessageContaining("already started");
    }

    @Test
    void cancel_twice_returnsConflict() {
        Booking b = existingBooking(alice, TOMORROW_10, TOMORROW_11);
        b.setStatus(BookingStatus.CANCELLED);
        when(bookings.findWithDetailsById(42L)).thenReturn(Optional.of(b));

        assertThatThrownBy(() -> service.cancel(alice, 42L)).isInstanceOf(ConflictException.class);
    }
}
