package com.portfolio.roombooking.user;

import jakarta.persistence.*;
import org.springframework.security.core.GrantedAuthority;
import org.springframework.security.core.authority.SimpleGrantedAuthority;
import org.springframework.security.core.userdetails.UserDetails;

import java.time.Instant;
import java.util.Collection;
import java.util.List;

/**
 * An account that can log in (table {@code users}).
 *
 * <p><b>Where it fits:</b> the JWT filter loads this entity on every authenticated request and stores
 * it in Spring Security's "security context". Controllers then receive it with
 * {@code @AuthenticationPrincipal User user}, and services use it to check ownership
 * ("is this booking yours?") and role ("are you an admin?").
 *
 * <p>It implements Spring Security's {@link UserDetails} interface, so Spring can use our own entity
 * directly as the logged-in principal - no separate adapter class is needed.
 *
 * <p>{@code @Entity} tells JPA/Hibernate "instances of this class are rows in a table".
 * {@code @Table(name = "users")} picks the table name ("user" is a reserved word in PostgreSQL,
 * hence the plural).
 */
@Entity
@Table(name = "users")
public class User implements UserDetails {

    /**
     * Primary key. {@code IDENTITY} means the database generates the value (the
     * "GENERATED BY DEFAULT AS IDENTITY" column in V1__create_tables.sql) when the row is inserted.
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @Column(nullable = false, length = 100)
    private String name;

    @Column(nullable = false, unique = true, length = 255)
    private String email;

    /** BCrypt hash of the password. The plain password is never stored anywhere. */
    @Column(name = "password_hash", nullable = false)
    private String passwordHash;

    /** Stored as the text 'USER' or 'ADMIN' (see {@link Role} for why STRING and not ORDINAL). */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private Role role = Role.USER;

    @Column(name = "created_at", nullable = false)
    private Instant createdAt = Instant.now();

    /** JPA needs a no-argument constructor to create instances when reading rows. {@code protected} hides it from our code. */
    protected User() {
    }

    /** Creates a regular {@link Role#USER} account. */
    public User(String name, String email, String passwordHash) {
        this(name, email, passwordHash, Role.USER);
    }

    public User(String name, String email, String passwordHash, Role role) {
        this.name = name;
        this.email = email;
        this.passwordHash = passwordHash;
        this.role = role;
    }

    public Long getId() { return id; }
    public String getName() { return name; }
    public String getEmail() { return email; }
    public Role getRole() { return role; }
    public Instant getCreatedAt() { return createdAt; }

    /** Convenience check used by services for "admins may do anything" rules. */
    public boolean isAdmin() {
        return role == Role.ADMIN;
    }

    // ----- UserDetails (what Spring Security needs to know about a principal) -----

    /**
     * The permissions of this user. We have exactly one: the role, e.g. {@code ROLE_ADMIN}.
     * {@code @PreAuthorize("hasRole('ADMIN')")} checks against this list.
     */
    @Override
    public Collection<? extends GrantedAuthority> getAuthorities() {
        return List.of(new SimpleGrantedAuthority(role.authority()));
    }

    @Override
    public String getPassword() { return passwordHash; }

    /** Spring calls the login identifier "username"; for us it is the email address. */
    @Override
    public String getUsername() { return email; }
}
